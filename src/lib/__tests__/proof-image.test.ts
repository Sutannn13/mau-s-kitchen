import { describe, expect, it, vi } from "vitest";

import {
  MAX_PROOF_SIZE_BYTES,
  validateProofImage,
} from "@/lib/proof-image";

function fakeFile(bytes: Uint8Array | number[]) {
  const data = Uint8Array.from(bytes);
  return {
    size: data.byteLength,
    async arrayBuffer() {
      return data.buffer;
    },
  };
}

const JPEG_FIXTURE = [
  0xff, 0xd8,
  0xff, 0xc0, 0x00, 0x0b, 0x08, 0x00, 0x01, 0x00, 0x01, 0x01, 0x01, 0x11,
  0x00,
  0xff, 0xda, 0x00, 0x08, 0x01, 0x01, 0x00, 0x00, 0x3f, 0x00,
  0x00,
  0xff, 0xd9,
];

const PNG_FIXTURE = [
  0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a,
  0x00, 0x00, 0x00, 0x0d, 0x49, 0x48, 0x44, 0x52,
  0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01,
  0x08, 0x06, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x01, 0x49, 0x44, 0x41, 0x54,
  0x00,
  0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4e, 0x44,
  0xae, 0x42, 0x60, 0x82,
];

const WEBP_FIXTURE = [
  0x52, 0x49, 0x46, 0x46, 0x12, 0x00, 0x00, 0x00,
  0x57, 0x45, 0x42, 0x50,
  0x56, 0x50, 0x38, 0x4c, 0x05, 0x00, 0x00, 0x00,
  0x2f, 0x00, 0x00, 0x00, 0x00,
  0x00,
];

describe("validateProofImage", () => {
  it("menerima JPEG, PNG, dan WebP dengan struktur dasar valid", async () => {
    await expect(validateProofImage(fakeFile(JPEG_FIXTURE))).resolves.toMatchObject({
      extension: "jpg",
      mimeType: "image/jpeg",
    });
    await expect(validateProofImage(fakeFile(PNG_FIXTURE))).resolves.toMatchObject({
      extension: "png",
      mimeType: "image/png",
    });
    await expect(validateProofImage(fakeFile(WEBP_FIXTURE))).resolves.toMatchObject({
      extension: "webp",
      mimeType: "image/webp",
    });
  });

  it("menolak HTML yang diganti nama dan MIME-nya menjadi gambar", async () => {
    const fakeJpeg = fakeFile([0x3c, 0x68, 0x74, 0x6d, 0x6c, 0x3e]);
    await expect(validateProofImage(fakeJpeg)).resolves.toBeNull();
  });

  it("menolak file yang hanya menempelkan signature JPEG", async () => {
    const spoofedHeader = fakeFile([
      0xff, 0xd8, 0xff, 0xe0, 0x00, 0x02, 0x3c, 0x68, 0x74, 0x6d, 0x6c, 0x3e,
      0xff, 0xd9,
    ]);
    await expect(validateProofImage(spoofedHeader)).resolves.toBeNull();
  });

  it("menolak berkas di atas 1MB sebelum membaca isinya", async () => {
    const arrayBuffer = vi.fn(async () => new ArrayBuffer(0));
    await expect(
      validateProofImage({
        size: MAX_PROOF_SIZE_BYTES + 1,
        arrayBuffer,
      }),
    ).resolves.toBeNull();
    expect(arrayBuffer).not.toHaveBeenCalled();
  });

  it("menolak berkas kosong dan container WebP yang terpotong", async () => {
    await expect(validateProofImage(fakeFile([]))).resolves.toBeNull();
    await expect(
      validateProofImage(
        fakeFile([
          0x52, 0x49, 0x46, 0x46, 0x20, 0x00, 0x00, 0x00,
          0x57, 0x45, 0x42, 0x50, 0x56, 0x50, 0x38, 0x4c,
        ]),
      ),
    ).resolves.toBeNull();
  });
});
